// Generates the browser copy of the price catalogue + live-price runtime.
//   node builder/gen-price-lines.js
// Outputs: assets/js/price-lines.js (website + admin panel) and android-app/www/price-lines.js (patient app)
const fs = require('fs');
const path = require('path');
const { APP_RATE_CHART_KEYS, LINES, WEBSITE_PAGE_CONTEXT, WEBSITE_PATH_CONTEXT, APP_ITEM_CONTEXT } = require('./data/price_lines.js');

const ROOT = path.join(__dirname, '..');
const cfg = fs.readFileSync(path.join(ROOT, 'android-partner/www/firebase-config.js'), 'utf8');
const pick = k => cfg.match(new RegExp(k + ':\\s*"([^"]+)"'))[1];

const runtime = fs.readFileSync(path.join(__dirname, 'price-runtime.js'), 'utf8')
  .replace('__PROJECT_ID__', pick('projectId'))
  .replace('__API_KEY__', pick('apiKey'));

const out =
  '// GENERATED by builder/gen-price-lines.js - do not edit by hand.\n' +
  'const PRICE_LINES = ' + JSON.stringify(LINES) + ';\n' +
  'const WEBSITE_PAGE_CONTEXT = ' + JSON.stringify(WEBSITE_PAGE_CONTEXT) + ';\n' +
  'const WEBSITE_PATH_CONTEXT = ' + JSON.stringify(WEBSITE_PATH_CONTEXT) + ';\n' +
  'const APP_RATE_CHART_KEYS = ' + JSON.stringify(APP_RATE_CHART_KEYS) + ';\n' +
  'const APP_ITEM_CONTEXT = ' + JSON.stringify(APP_ITEM_CONTEXT) + ';\n' +
  runtime;

fs.writeFileSync(path.join(ROOT, 'assets/js/price-lines.js'), out);
const appDir = path.join(ROOT, 'android-app/www');
if (fs.existsSync(appDir)) fs.writeFileSync(path.join(appDir, 'price-lines.js'), out);
console.log('price-lines.js written (' + LINES.length + ' price lines)');
